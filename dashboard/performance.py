import streamlit as st
import pandas as pd
import plotly.express as px
from pathlib import Path
from dashboard.components import page_header

ROOT = Path(__file__).resolve().parents[1]
page_header("RESQ AI / INTELLIGENCE", "Agent Performance", "Compare Random, Rule-Based and Double DQN using repeatable evaluation episodes.")
episodes = st.number_input("Evaluation episodes per agent", min_value=5, max_value=500, value=30, step=5)
if st.button("Run evaluation", type="primary"):
    import subprocess, sys
    result = subprocess.run([sys.executable,str(ROOT/"evaluation/evaluator.py"),"--episodes",str(int(episodes))],
                            cwd=ROOT,capture_output=True,text=True)
    if result.returncode == 0: st.success(result.stdout)
    else: st.error(result.stderr[-3000:])
path = ROOT/"data/evaluation_results/comparison.csv"
if path.exists():
    df = pd.read_csv(path)
    if not df.empty:
        summary = df.groupby("agent").agg(
            mean_reward=("reward","mean"), mean_rescued=("rescued","mean"),
            critical_rescued=("critical_rescued","mean"), success_rate=("success","mean"),
            survival_rate=("survived","mean"), mean_steps=("steps","mean"),
            mean_hazards=("hazard_encounters","mean")).reset_index()
        st.subheader("Evaluation summary")
        st.dataframe(summary.style.format({"mean_reward":"{:.2f}","mean_rescued":"{:.2f}","success_rate":"{:.1%}","survival_rate":"{:.1%}"}),use_container_width=True)
        metric = st.selectbox("Chart metric",["rescued","reward","critical_rescued","steps","hazard_encounters"])
        st.plotly_chart(px.box(df,x="agent",y=metric,color="agent",points="all",title=f"Agent comparison: {metric}"),use_container_width=True)
        st.plotly_chart(px.bar(summary,x="agent",y="mean_rescued",title="Average victims rescued"),use_container_width=True)
        st.caption("Results are generated by running the selected agents. If no trained checkpoint exists, Double DQN uses its untrained initialized network.")
        st.dataframe(df,use_container_width=True)
else:
    st.info("No evaluation results found. Run an evaluation to create a comparison dataset.")
